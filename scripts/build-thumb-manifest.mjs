// Erzeugt eine TypeScript-Datei mit der Liste aller existierenden Thumbnails.
// Wird als Prebuild-Step ausgeführt, damit MediaCard / FaktencheckCard
// die Existenz von Thumbnails prüfen können, ohne `node:fs` zur Render-Zeit
// zu importieren (was in Cloudflare Workers nicht funktioniert).
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const dirs = {
  articleThumbs: 'public/article-thumbs',
  faktencheckThumbs: 'public/faktencheck-thumbs',
  ytThumbs: 'public/yt-thumbs',
  chronikThumbs: 'public/chronik-thumbs',
};

const result = {};
for (const [key, dir] of Object.entries(dirs)) {
  try {
    const files = await readdir(join(root, dir));
    result[key] = files
      .filter((f) => /\.(jpg|jpeg|png|webp)$/i.test(f))
      .sort();
  } catch {
    result[key] = [];
  }
}

await mkdir(join(root, 'src/data'), { recursive: true });
const out = `// Auto-generated by scripts/build-thumb-manifest.mjs (prebuild step).
// Don't edit by hand.
export const thumbManifest = ${JSON.stringify(result, null, 2)} as const;
`;
await writeFile(join(root, 'src/data/thumb-manifest.ts'), out);
console.log(
  `thumb-manifest: ${Object.entries(result)
    .map(([k, v]) => `${k}=${v.length}`)
    .join(' · ')}`,
);
